import React, { useState } from 'react';
import { useMechLab } from '../context/MechLabContext';
import GenerateTrackBar from '../components/shared/GenerateTrackBar';

export default function ProjectsScreen({ active }) {
  const {
    navTo,
    showToast,
    selectTrackByTitleOrKey,
    openBotWithPrompt,
    customProjects,
  } = useMechLab();
  const [searchQuery, setSearchQuery] = useState('');

  const handleOpenProjectTrack = (keyOrTitle) => {
    selectTrackByTitleOrKey('project', keyOrTitle);
    navTo('project');
  };

  const baseProjects = [
    {
      key: 'obstacle',
      icon: '🚧',
      title: 'Obstacle-Avoiding Robot',
      subtitle: 'Ultrasonic sensor · Intermediate',
      progress: 40,
      meta: 'Step 3 of 6',
      btnLabel: 'Continue',
      locked: false,
    },
    {
      key: 'linecar',
      icon: '✅',
      title: 'Line-Following Car',
      subtitle: 'IR sensors · Beginner',
      progress: 100,
      meta: '6 / 6 steps',
      btnLabel: 'View project',
      locked: false,
    },
    {
      key: 'temp',
      icon: '🌡️',
      title: 'Temperature Alarm',
      subtitle: 'Microcontroller · Beginner',
      progress: 0,
      meta: '0 / 5 steps',
      btnLabel: 'Start',
      locked: false,
    },
    {
      key: 'handsign-locked',
      icon: '🔒',
      title: 'Hand-Sign Robot',
      subtitle: 'AI + motors · Advanced',
      progress: 0,
      meta: 'Locked',
      btnLabel: 'Locked',
      locked: true,
      toast: 'Finish the Obstacle-Avoiding Robot to unlock this project',
    },
  ];

  const q = searchQuery.trim().toLowerCase();
  const filtered = baseProjects.filter(
    (p) =>
      !q ||
      p.title.toLowerCase().includes(q) ||
      p.subtitle.toLowerCase().includes(q)
  );

  return (
    <section className={`screen${active ? ' show' : ''}`} id="projects">
      <div className="hdr">
        <h1>Learn</h1>
      </div>
      <div className="chips">
        <button
          className="chip"
          type="button"
          aria-pressed="false"
          onClick={() => navTo('courses')}
        >
          Courses
        </button>
        <button
          className="chip"
          type="button"
          aria-pressed="true"
          onClick={() => navTo('projects')}
        >
          Projects
        </button>
      </div>
      <GenerateTrackBar />
      <input
        className="f"
        type="search"
        placeholder="Search projects..."
        aria-label="Search projects"
        value={searchQuery}
        onChange={(e) => setSearchQuery(e.target.value)}
      />
      <div className="courses">
        {customProjects.map((cp) => (
          <div className="course" key={cp.key}>
            <div
              className="ct"
              style={{
                background: 'var(--tile)',
                display: 'grid',
                placeItems: 'center',
                aspectRatio: '3/2',
                fontSize: '2.4rem',
              }}
            >
              🛠️
            </div>
            <div className="cb">
              <h3>{cp.title}</h3>
              <p>Generated by Mech Bot · {cp.stopsCount} steps</p>
              <div className="bar">
                <i style={{ width: '0%' }} />
              </div>
              <div className="cf">
                <span className="meta">0 / {cp.stopsCount} steps</span>
                <button
                  className="go"
                  type="button"
                  onClick={() => handleOpenProjectTrack(cp.key)}
                >
                  Start
                </button>
              </div>
            </div>
          </div>
        ))}

        {filtered.map((proj) => (
          <div className="course" key={proj.key}>
            <div
              className="ct"
              style={{
                background: 'var(--tile)',
                display: 'grid',
                placeItems: 'center',
                aspectRatio: '3/2',
                fontSize: '2.4rem',
              }}
            >
              {proj.icon}
            </div>
            <div className="cb">
              <h3>{proj.title}</h3>
              <p>{proj.subtitle}</p>
              <div className="bar">
                <i style={{ width: `${proj.progress}%` }} />
              </div>
              <div className="cf">
                <span className="meta">{proj.meta}</span>
                {proj.locked ? (
                  <button
                    className="go lk"
                    type="button"
                    onClick={() => showToast(proj.toast)}
                  >
                    {proj.btnLabel}
                  </button>
                ) : (
                  <button
                    className="go"
                    type="button"
                    onClick={() => handleOpenProjectTrack(proj.key)}
                  >
                    {proj.btnLabel}
                  </button>
                )}
              </div>
            </div>
          </div>
        ))}
      </div>
      <button
        className="btn g"
        type="button"
        onClick={() => openBotWithPrompt('Suggest a project for me')}
      >
        Ask Mech Bot to suggest a project
      </button>
    </section>
  );
}
